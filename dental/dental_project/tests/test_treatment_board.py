from odoo.exceptions import UserError
from odoo.tests import Form, tagged

from odoo.addons.dental_core.tests.test_consultation_workflow import ConsultationCommon


@tagged('post_install', '-at_install', 'dental_project')
class TestTreatmentBoard(ConsultationCommon):

    @classmethod
    def setUpClass(cls):
        super().setUpClass()
        cls.env['product.template']._dental_set_delivery_invoicing()
        cls.Stage = cls.env['project.task.type']
        cls.stages = cls.Stage._dental_board_stages()

    def _plan_with_phases(self):
        """A plan built on its board: two phases, each with its treatments."""
        case = self._visit().case_id
        action = case.action_new_treatment_plan()
        self.assertEqual(action['res_model'], 'project.task', "New Plan opens the plan's board")
        project = self.env['project.project'].browse(action['context']['default_project_id'])
        plan = project.dental_plan_id
        Task = self.env['project.task'].with_context(action['context'])
        phase_1 = Task.create({'name': 'Phase 1 · Disease control'})
        phase_2 = Task.create({'name': 'Phase 2 · Restorative'})
        phase_1.write({'dental_line_ids': [
            (0, 0, {'treatment_id': self.treatment.id, 'tooth_reference': '36', 'unit_price': 100.0}),
        ]})
        phase_2.write({'dental_line_ids': [
            (0, 0, {'treatment_id': self.treatment_2.id, 'tooth_reference': '46', 'unit_price': 300.0,
                    'number_of_visits': 2}),
        ]})
        return plan, phase_1, phase_2

    def test_new_plan_opens_a_board_of_phases(self):
        plan, phase_1, phase_2 = self._plan_with_phases()
        project = plan.project_id
        self.assertEqual(len(self.stages), 3)
        self.assertEqual(project.type_ids, self.stages)
        self.assertEqual(project.partner_id, self.patient)
        self.assertEqual(plan.dental_phase_ids, phase_1 | phase_2)
        self.assertLess(phase_1.sequence, phase_2.sequence, "New phases go after the existing ones")
        self.assertEqual(phase_1.stage_id.dental_board_state, 'planned')
        filling = phase_1.dental_line_ids
        self.assertEqual(filling.plan_id, plan, "A treatment added to a phase belongs to its plan")
        self.assertEqual(len(plan.line_ids), 2)
        self.assertEqual(phase_2.dental_amount, 300.0)
        self.assertIn('46', phase_2.dental_treatment_summary)
        self.assertEqual(plan.step_summary, '0 of 2 phases done')

    def test_phase_form_adds_treatments(self):
        plan, phase_1, _phase_2 = self._plan_with_phases()
        with Form(phase_1.with_context(form_view_ref='dental_project.view_task_form_dental')) as form:
            with form.dental_line_ids.new() as line:
                line.treatment_id = self.treatment_2
                line.tooth_reference = '11'
        added = phase_1.dental_line_ids.filtered(lambda l: l.tooth_reference == '11')
        self.assertEqual(added.plan_id, plan)
        self.assertEqual(added.unit_price, self.treatment_2.list_price, "Price comes from the treatment")

    def test_treatment_outside_a_phase_gets_one(self):
        plan, _phase_1, _phase_2 = self._plan_with_phases()
        line = self.env['dental.treatment.plan.line'].create({
            'plan_id': plan.id, 'treatment_id': self.treatment.id, 'phase': '4'})
        self.assertTrue(line.phase_task_id)
        self.assertEqual(line.phase_task_id.project_id, plan.project_id)

    def test_phase_moves_with_visits_and_one_quotation(self):
        plan, phase_1, phase_2 = self._plan_with_phases()
        plan.action_propose()
        plan.action_accept()
        order = plan.sale_order_id
        self.assertEqual(order.state, 'sale')
        self.assertEqual(len(order.order_line), 2)
        filling, rct = phase_1.dental_line_ids, phase_2.dental_line_ids
        self.assertEqual(rct.sale_line_id.task_id, phase_2)
        self.assertEqual(rct.sale_line_id.price_unit, 300.0)
        self.assertFalse(order.project_ids - plan.project_id, "No extra project generated by the sale")

        # First of two visits: the phase is in progress, half delivered, nothing billed directly
        rct.action_mark_visit_done()
        self.assertEqual(phase_2.stage_id.dental_board_state, 'in_progress')
        self.assertEqual(rct.sale_line_id.qty_delivered, 0.5)
        self.assertEqual(rct.session_ids.filtered(lambda s: s.state == 'completed').billing_state, 'sale_order')
        self.assertFalse(plan.case_id._get_billable_sessions(), "Nothing to invoice directly from the case")

        # Phase dragged to Done: the remaining visit is recorded
        phase_2.stage_id = self.Stage._dental_stage_for('done')
        self.assertEqual(phase_2.state, '1_done')
        self.assertEqual(rct.state, 'completed')
        self.assertEqual(rct.sale_line_id.qty_delivered, 1.0)
        with self.assertRaises(UserError):
            phase_2.stage_id = self.Stage._dental_stage_for('in_progress')

        # Last treatment of a phase completed: the phase is done by itself
        filling.action_mark_visit_done()
        self.assertEqual(phase_1.state, '1_done')
        self.assertEqual(phase_1.stage_id.dental_board_state, 'done')
        self.assertEqual(plan.state, 'completed')

    def test_treatment_added_after_acceptance_goes_on_the_order(self):
        plan, phase_1, _phase_2 = self._plan_with_phases()
        plan.action_accept()
        phase_1.write({'dental_line_ids': [(0, 0, {'treatment_id': self.treatment.id, 'tooth_reference': '37'})]})
        added = phase_1.dental_line_ids.filtered(lambda l: l.tooth_reference == '37')
        self.assertEqual(added.acceptance, 'accepted')
        self.assertEqual(added.sale_line_id.order_id, plan.sale_order_id)

    def test_cancelled_phase_leaves_the_order(self):
        plan, phase_1, phase_2 = self._plan_with_phases()
        plan.action_accept()
        filling_sol = phase_1.dental_line_ids.sale_line_id
        phase_1.state = '1_canceled'
        self.assertEqual(phase_1.dental_line_ids.acceptance, 'declined')
        self.assertEqual(filling_sol.product_uom_qty, 0.0)
        self.assertEqual(plan.step_summary, '0 of 1 phases done')

    def test_phase_with_visits_done_cannot_be_deleted(self):
        _plan, phase_1, phase_2 = self._plan_with_phases()
        phase_1.dental_line_ids.action_mark_visit_done()
        with self.assertRaises(UserError):
            phase_1.unlink()
        line = phase_2.dental_line_ids
        phase_2.unlink()
        self.assertFalse(line.exists(), "Deleting an untouched phase removes its treatments")

    def test_each_phase_has_its_own_invoice(self):
        if not self.env['account.journal'].search([('type', '=', 'sale'), ('company_id', '=', self.env.company.id)], limit=1):
            self.skipTest("No sales journal in this database")
        plan, phase_1, phase_2 = self._plan_with_phases()
        plan.action_accept()
        order = plan.sale_order_id
        phase_1.dental_line_ids.action_mark_visit_done()
        self.assertTrue(phase_1.dental_to_invoice)
        self.assertFalse(phase_2.dental_to_invoice)
        phase_1.action_dental_create_invoice()
        self.assertEqual(phase_1.dental_invoice_count, 1)
        self.assertEqual(phase_1.dental_invoice_ids.invoice_line_ids.sale_line_ids, phase_1.dental_line_ids.sale_line_id)

        # Phase 2 done, then invoiced from the order's own button: still an invoice per phase
        phase_2.stage_id = self.Stage._dental_stage_for('done')
        self.env['project.task'].invalidate_model()
        phase_1.dental_line_ids.write({'number_of_visits': 1})
        invoices = order._create_invoices()
        self.assertEqual(len(invoices), 1)
        self.assertEqual(invoices.invoice_line_ids.sale_line_ids, phase_2.dental_line_ids.sale_line_id)
        self.assertNotEqual(phase_1.dental_invoice_ids, phase_2.dental_invoice_ids)

    def test_new_phase_after_completed_phases(self):
        plan, phase_1, phase_2 = self._plan_with_phases()
        plan.action_accept()
        phase_1.stage_id = self.Stage._dental_stage_for('done')
        phase_2.stage_id = self.Stage._dental_stage_for('done')
        self.assertEqual(plan.state, 'completed')
        phase_3 = self.env['project.task'].with_context(plan.action_dental_open_board()['context']).create(
            {'name': 'Phase 3 · Maintenance'})
        phase_3.write({'dental_line_ids': [(0, 0, {'treatment_id': self.treatment.id, 'tooth_reference': '21'})]})
        self.assertEqual(plan.state, 'in_progress', "Adding a treatment reopens the finished plan")
        line = phase_3.dental_line_ids
        self.assertEqual(line.acceptance, 'accepted')
        self.assertEqual(line.sale_line_id.order_id, plan.sale_order_id)
        line.action_mark_visit_done()
        self.assertEqual(phase_3.state, '1_done')

    def test_board_views_carry_the_dentist_domain_fields(self):
        # user_ids' domain reads project_sharing_portal_user_ids / company_id on the client
        for xmlid in ('view_task_kanban_dental', 'view_task_list_dental', 'view_task_form_dental'):
            arch = self.env['project.task'].get_view(self.env.ref(f'dental_project.{xmlid}').id)['arch']
            self.assertIn('project_sharing_portal_user_ids', arch, xmlid)
